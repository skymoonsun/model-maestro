@router.post("/assistant/api/v1/chats/{chat_id}/messages", include_in_schema=True)
async def grafana_create_message(request: Request, chat_id: str):
    """Grafana Assistant — Create messages in a chat"""
    log = await _log_grafana_request(request)
    body = log.get("body")
    if isinstance(body, list):
        messages = body
    elif isinstance(body, dict):
        messages = [body]
    else:
        messages = []

    created: list[Dict[str, Any]] = []
    for msg in messages:
        chat = await grafana_chat_store.get_chat(chat_id)
        if not chat:
            await grafana_chat_store.create_chat()
            chat = await grafana_chat_store.get_chat(chat_id)
            if not chat:
                await grafana_chat_store.create_chat()
                grafana_chat_store._chats[chat_id] = grafana_chat_store._chats.pop(list(grafana_chat_store._chats.keys())[-1])
                grafana_chat_store._chats[chat_id]["id"] = chat_id
        await grafana_chat_store.add_message(chat_id, msg)
        created.append(msg)

    return JSONResponse(
        status_code=200,
        content={
            "$schema": "https://assistant-prod-eu-central-0.grafana.net/schemas/ResponseBodyListMessage.json",
            "status": "success",
            "data": created,
        },
    )


