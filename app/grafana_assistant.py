async def _grafana_chats_create_impl(request: Request) -> JSONResponse:
    """Shared implementation for creating a Grafana chat."""
    log_record = await _log_grafana_request(request)
    body = log_record.get("body") or {}

    chat = await grafana_chat_store.create_chat()
    # Override with client-provided defaults
    if "name" in body:
        chat["name"] = body["name"]
    if "nameAutogenerated" in body:
        chat["nameAutogenerated"] = body["nameAutogenerated"]
    if "origin" in body:
        chat["source"] = body["origin"].replace("oss/", "")

    return JSONResponse(
        status_code=200,
        content={
            "$schema": "https://assistant-prod-eu-central-0.grafana.net/schemas/ResponseBodyChatResponse.json",
            "status": "success",
            "data": chat,
        },
    )


async def _grafana_chats_list_impl(
    includeArchived: Optional[bool] = None,
    sources: Optional[list] = None,
    limit: Optional[int] = None,
    offset: Optional[int] = None,
) -> JSONResponse:
    """Shared implementation for listing Grafana chats."""
    chats = await grafana_chat_store.list_chats(
        include_archived=includeArchived if includeArchived is not None else False,
        sources=sources,
    )

    # If store is empty and no explicit pagination, auto-create a chat and
    # return single-chat format (Grafana expects this when opening the panel).
    if not chats and limit is None and offset is None:
        chat = await grafana_chat_store.create_chat()
        return JSONResponse(
            status_code=200,
            content={
                "$schema": "https://assistant-prod-eu-central-0.grafana.net/schemas/ResponseBodyChatResponse.json",
                "status": "success",
                "data": chat,
            },
        )

    # Normal list mode
    count = len(chats)
    effective_limit = limit if limit is not None else 50
    effective_offset = offset if offset is not None else 0
    items = chats[effective_offset : effective_offset + effective_limit]
    return JSONResponse(
        status_code=200,
        content={
            "$schema": "https://assistant-prod-eu-central-0.grafana.net/schemas/ResponseBodyListResponseChat.json",
            "status": "success",
            "data": {
                "items": items,
                "pagination": {"total": count, "limit": effective_limit, "offset": effective_offset},
            },
        },
    )


