# Chat Memory Store (in-memory, per-process)
# ============================================================================

class _GrafanaChatStore:
    def __init__(self) -> None:
        self._chats: Dict[str, Any] = {}
        self._lock = asyncio.Lock()

    async def create_chat(self) -> Dict[str, Any]:
        chat_id = str(uuid.uuid4())
        now = datetime.datetime.utcnow().isoformat(timespec="milliseconds") + "Z"
        chat: Dict[str, Any] = {
            "id": chat_id,
            "created": now,
            "modified": now,
            "userId": "admin@localhost",
            "name": "New Chat",
            "nameAutogenerated": True,
            "category": "Other",
            "archived": False,
            "isPublic": False,
            "isImported": False,
            "inputTokens": 0,
            "outputTokens": 0,
            "cacheCreationInputTokens": 0,
            "cacheReadInputTokens": 0,
            "source": "assistant",
            "lastMode": "dashboarding",
            "messages": [],
        }
        async with self._lock:
            self._chats[chat_id] = chat
        return chat

    async def get_chat(self, chat_id: str) -> Any | None:
        async with self._lock:
            return self._chats.get(chat_id)

    async def add_message(self, chat_id: str, msg: Dict[str, Any]) -> Dict[str, Any]:
        msg.setdefault("id", str(uuid.uuid4()))
        msg.setdefault("created", datetime.datetime.utcnow().isoformat(timespec="milliseconds") + "Z")
        msg.setdefault("modified", msg["created"])
        msg.setdefault("type", "message")
        msg.setdefault("hidden", False)
        async with self._lock:
            chat = self._chats[chat_id]
            chat["messages"].append(msg)
            chat["modified"] = msg["created"]
        return msg

    async def list_chats(
        self,
        include_archived: bool = False,
        sources: Optional[list[str]] = None,
    ) -> list[Dict[str, Any]]:
        async with self._lock:
            chats = list(self._chats.values())
        if not include_archived:
            chats = [c for c in chats if not c.get("archived", False)]
        if sources is not None:
            chats = [c for c in chats if c.get("source") in sources]
        return chats


grafana_chat_store = _GrafanaChatStore()


