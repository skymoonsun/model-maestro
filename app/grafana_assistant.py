@router.api_route("/{path:path}", methods=["GET", "POST", "PUT", "DELETE", "PATCH", "HEAD", "OPTIONS"])
async def grafana_catch_all(request: Request, path: str = ""):
    """Catch-all for unhandled Grafana Assistant paths. Logs for discovery."""
    await _log_grafana_request(request)
    return JSONResponse(
        status_code=200,
        content={"status": "received", "method": request.method, "path": path, "logged": True},
    )
